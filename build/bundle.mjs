// Build step (runs before Eleventy). Two jobs:
//  1. Generate lib/corpus.generated.mjs from _data/ so the Netlify function
//     imports the corpus as bundled code — no fragile runtime fs in the lambda.
//  2. Bundle the AskMike chat widget into js/chat.bundle.js, sharing the CDN's
//     React via the react-shim alias (single instance).
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (rel) => readFileSync(root + rel, 'utf8');

// 1. corpus module
const corpus = {
  profile: read('_data/profile.md'),
  projects: JSON.parse(read('_data/projects.json')),
  site: JSON.parse(read('_data/site.json')),
};
writeFileSync(
  root + 'lib/corpus.generated.mjs',
  `// AUTO-GENERATED by build/bundle.mjs from _data/. Do not edit.\nexport const CORPUS = ${JSON.stringify(corpus)};\n`,
);

// 2. chat widget bundle
await build({
  entryPoints: [root + 'js/chat.jsx'],
  bundle: true,
  format: 'iife',
  outfile: root + 'js/chat.bundle.js',
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  alias: {
    react: root + 'build/react-shim.mjs',
    'react/jsx-runtime': root + 'build/react-jsx-runtime-shim.mjs',
  },
  minify: true,
  target: 'es2020',
  logLevel: 'info',
});

console.log('built js/chat.bundle.js + lib/corpus.generated.mjs');
